import assert from 'node:assert/strict';
import { safeRoute, resourceKind, summarize, VIEWS, REPORTS } from './observer.mjs';
const origin = 'https://salla-analytics.preview.emergentagent.com';
assert.equal(Object.keys(VIEWS).length, 8);
assert.equal(Object.keys(REPORTS).length, 12);
const route = safeRoute('/operational-balances?view=reports&report_tab=couriers&id=PRIVATE&token=SECRET#CUSTOMER', origin);
assert.deepEqual(route, { path: '/operational-balances', view: 'reports', report_tab: 'couriers', key: '/operational-balances?view=reports&report_tab=couriers' });
assert.equal(safeRoute('https://attacker.example/operational-balances?view=reports', origin), null);
assert.equal(safeRoute('/operational-balances?view=entry&id=PRIVATE', origin), null);
assert.equal(safeRoute('/operational-balances?view=reports&report_tab=PRIVATE', origin), null);
assert.equal(safeRoute('/operational-balances/daily-movements?id=PRIVATE', origin), null);
assert.equal(safeRoute('/operational-balances/daily-movements', origin).view, 'log');
assert.equal(resourceKind('/pr2095/api/operational-balances/workspace/read-demand/PRIVATE?token=SECRET', origin), 'workspace/read-demand/:redacted');
assert.equal(resourceKind('/api/operational-balances/accounts/PRIVATE', origin), 'operational-other');
assert.equal(resourceKind('/api/auth/login?password=PRIVATE', origin), null);
assert.equal(resourceKind('https://other.example/api/auth/me', origin), null);
assert.deepEqual(summarize([]), { n: 0, p50_ms: null, p95_ms: null, p95_unavailable_reason: 'fewer_than_20_valid_samples', max_ms: null });
assert.equal(summarize([1, 2, 9, 20]).p50_ms, 5.5);
assert.equal(summarize([1, 2, 9, 20]).p95_ms, null);
const values = Array.from({ length: 20 }, (_, i) => i + 1);
assert.equal(summarize(values).p50_ms, 10.5);
assert.equal(summarize(values).p95_ms, 19);
assert.equal(summarize([NaN, Infinity, -1, 0, 1]).n, 2);
console.log('PASS: route confidentiality, read-only route allowlist, resource redaction, sample counts and independent percentile oracles');
